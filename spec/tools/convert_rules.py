"""Convert the BF-CBOM Java/Python Crypistry rules into the CipherSift rule format.

Only the rules written by BF-CBOM are read:
  rules/discovery/invocation/source/src.java.*.yaml
  rules/discovery/invocation/source/src.python.*.yaml
  rules/discovery/invocation/dependency/dep.python.*.yaml   (package lists only)

Usage:
  python3 convert_rules.py --registry <crypistry dir> --out <ciphersift repo>/rules

Writes rules/java/<id>.yaml, rules/python/<id>.yaml and rules/dependencies/dep.pypi.yaml.
The Maven package list (rules/dependencies/dep.maven.yaml) and the Java constant
table (rules/java/_constants.yaml) are not converted; they are maintained by hand
in this repository and are left untouched.

The conversion is purely mechanical (key renaming, enum mapping); it fails on
any key it does not know, so a change in the source format cannot slip through.
Requires PyYAML.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

HEADER = (
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Copyright 2026 The CipherSift Authors\n"
    "# Generated by spec/tools/convert_rules.py from the BF-CBOM rule {src}; do not edit by hand.\n"
)

# rule primitive (Crypistry spelling) -> CycloneDX 1.6 algorithmProperties.primitive
PRIMITIVE = {
    None: None,
    "blockCipher": "block-cipher",
    "streamCipher": "stream-cipher",
    "keyAgreement": "key-agree",
    "keyDerivation": "kdf",
    "signature": "signature",
    "hash": "hash",
    "mac": "mac",
    "pke": "pke",
    "kem": "kem",
}

ASSET_TYPES = {"algorithm", "protocol", "certificate", "related-crypto-material", "key-material"}

# old matcher key -> new pattern key, per language
JAVA_KEYS = {
    "call": "call",
    "method": "method",
    "field_ref": "field",
    "method_decl": "override",
    "args_matches_regex": "firstString",
    "args_any_matches_regex": "anyString",
    "args_contains_string": "stringContains",
    "args_text_matches_regex": "argsText",
    "args_text_contains": "argsTextContains",
    "arg_is_constant": "constantArg",
    "in_type_implementing": "inType",
    "body_matches_regex": "body",
}
PYTHON_KEYS = {
    "call": "call",
    "method": "method",
    "args_matches_regex": "firstString",
    "args_contains_string": "stringContains",
    "args_contains_symbol": "anySymbol",
    "args_contains_all_symbols": "allSymbols",
    "kwarg_matches": "kwargs",
    "param_arg": "param",
    "report_at_enclosing_method": "reportAt",
    "field_assign": "assign",
    "value_matches_regex": "value",
    "value_contains": "valueContains",
}
LIST_KEYS = {"stringContains", "argsTextContains", "inType", "anySymbol", "allSymbols",
             "reportAt", "valueContains"}

# key order inside a written pattern (anchor first, then constraints, then non-filters)
ORDER = ["call", "new", "method", "field", "override", "assign", "anyCall",
         "firstString", "anyString", "stringContains", "argsText", "argsTextContains",
         "constantArg", "anySymbol", "allSymbols", "kwargs", "inType", "body",
         "value", "valueContains", "param", "reportAt"]


def die(msg: str) -> None:
    sys.exit(f"convert_rules: {msg}")


def as_list(v):
    return [v] if isinstance(v, str) else list(v)


def convert_pattern(m: dict, lang: str, src: str) -> dict:
    table = JAVA_KEYS if lang == "java" else PYTHON_KEYS
    out: dict = {}
    for k, v in m.items():
        if k not in table:
            die(f"{src}: unknown matcher key {k!r} for {lang}")
        nk = table[k]
        if nk in LIST_KEYS:
            v = as_list(v)
        if nk == "kwargs":
            v = {str(kk): str(vv) for kk, vv in v.items()}
        if nk == "param":
            v = {kk: v[kk] for kk in ("self", "keyword", "index") if kk in v}
        out[nk] = v
    if lang == "java" and "call" in out and out["call"].endswith(".new"):
        out["new"] = out.pop("call")[: -len(".new")]
    if lang == "python" and not any(k in out for k in ("call", "method", "assign")):
        if set(out) - {"kwargs"}:
            die(f"{src}: unanchored python matcher with keys {sorted(out)}")
        out["anyCall"] = True
    if lang == "python" and isinstance(out.get("method"), list) and len(out["method"]) == 1:
        out["method"] = out["method"][0]
    for rx_key in ("firstString", "anyString", "argsText", "body", "value"):
        if rx_key in out:
            check_regex(out[rx_key], src)
    for rx in (out.get("kwargs") or {}).values():
        check_regex(rx, src)
    return {k: out[k] for k in ORDER if k in out}


def check_regex(rx: str, src: str) -> None:
    try:
        re.compile(rx)
    except re.error as exc:
        die(f"{src}: bad regex {rx!r}: {exc}")
    # constructs whose meaning differs between Python re and java.util.regex
    for bad in ("(?P<", "(?P=", "\\Z", "(?#"):
        if bad in rx:
            die(f"{src}: regex {rx!r} uses Python-only syntax {bad!r}")


def convert_asset(ap: dict, src: str) -> dict:
    at = ap.get("asset_type")
    if at not in ASSET_TYPES:
        die(f"{src}: unknown asset_type {at!r}")
    prim = ap.get("primitive")
    if prim not in PRIMITIVE:
        die(f"{src}: unknown primitive {prim!r}")
    out = {"type": at}
    for k_old, k_new in (("asset_subtype", "subtype"),):
        if ap.get(k_old) is not None:
            out[k_new] = ap[k_old]
    if PRIMITIVE[prim] is not None:
        out["primitive"] = PRIMITIVE[prim]
    if ap.get("algorithm_family") is not None:
        out["family"] = ap["algorithm_family"]
    if ap.get("variant") is not None:
        out["variant"] = ap["variant"]
    if ap.get("classical_security_level_bits") is not None:
        out["securityLevel"] = int(ap["classical_security_level_bits"])
    if ap.get("protocol_type") is not None:
        out["protocol"] = ap["protocol_type"]
    if ap.get("version") is not None:
        out["version"] = str(ap["version"])
    known = {"asset_type", "asset_subtype", "primitive", "algorithm_family", "variant",
             "classical_security_level_bits", "protocol_type", "version"}
    if set(ap) - known:
        die(f"{src}: unknown asset_properties keys {sorted(set(ap) - known)}")
    return out


# Description sentences of the source rules that refer to rules outside the carried-over
# Java/Python set (e.g. the third-party Go rules); replaced so that no foreign rule id or
# source-format key name is published.
DESCRIPTION_REWRITES = {
    "Same asset_properties as src.go.rand.prng.insecure (related-crypto-material / prng-insecure); "
    "filter on that subtype or the rule id to drop them from an algorithm inventory.":
    "Asset type related-crypto-material, subtype prng-insecure; filter on that subtype or the "
    "rule id to drop them from an algorithm inventory.",
}


def clean_description(text: str, src: str) -> str:
    for old, new in DESCRIPTION_REWRITES.items():
        text = text.replace(old, new)
    for bad in ("src.go.", "src.ruby.", "asset_properties", "rule_identifier"):
        if bad in text:
            die(f"{src}: description mentions {bad!r}; add a rewrite")
    return text


def convert_source_rule(path: Path) -> tuple[str, str, dict]:
    d = yaml.safe_load(path.read_text(encoding="utf-8"))
    rid = d["rule_identifier"]
    m = re.fullmatch(r"src\.(java|python)\.(.+)", rid)
    if not m:
        die(f"{path.name}: unexpected rule id {rid}")
    lang = m.group(1)
    det = d["detector"]
    if det.get("language") != lang or det.get("scan_method") != "source-code-scan":
        die(f"{path.name}: detector does not match language {lang}")
    if set(det) - {"scan_method", "language", "file_globs", "match"}:
        die(f"{path.name}: unknown detector keys")
    if set(det["match"]) != {"any_of"}:
        die(f"{path.name}: match must only contain any_of")
    rule = {
        "id": f"{lang}.{m.group(2)}",
        "kind": "source",
        "language": lang,
        "name": d["name"],
        "description": clean_description(" ".join(str(d.get("description") or "").split()), path.name),
        "asset": convert_asset(d["asset_properties"], path.name),
        "match": [convert_pattern(p, lang, path.name) for p in det["match"]["any_of"]],
    }
    return lang, rule["id"], rule


def norm_pypi(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def convert_pypi(dep_dir: Path) -> dict:
    pkgs: list[str] = []
    sources = sorted(dep_dir.glob("dep.python.*.yaml"))
    if not sources:
        die(f"no dep.python.*.yaml in {dep_dir}")
    for f in sources:
        d = yaml.safe_load(f.read_text(encoding="utf-8"))
        for p in d["detector"].get("packages") or []:
            n = norm_pypi(p)
            if n not in pkgs:
                pkgs.append(n)
    return {"packages": pkgs, "sources": [f.name for f in sources]}


class Dumper(yaml.SafeDumper):
    pass


def _str(dumper, data):
    style = None
    if len(data) > 100 or "\n" in data:
        style = ">"
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


Dumper.add_representer(str, _str)


def dump(obj) -> str:
    return yaml.dump(obj, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=100,
                     default_flow_style=False)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--registry", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()
    src_dir = args.registry / "rules/discovery/invocation/source"
    dep_dir = args.registry / "rules/discovery/invocation/dependency"
    counts = {"java": 0, "python": 0}
    for lang in ("java", "python"):
        out_dir = args.out / lang
        out_dir.mkdir(parents=True, exist_ok=True)
        for old in out_dir.glob(f"{lang}.*.yaml"):
            old.unlink()
    seen: set[str] = set()
    for f in sorted(src_dir.glob("src.java.*.yaml")) + sorted(src_dir.glob("src.python.*.yaml")):
        lang, rid, rule = convert_source_rule(f)
        if rid in seen:
            die(f"duplicate id {rid}")
        seen.add(rid)
        text = HEADER.format(src=f.name) + dump(rule)
        (args.out / lang / f"{rid}.yaml").write_text(text, encoding="utf-8")
        counts[lang] += 1

    # PyPI: the BF-CBOM package list, merged with the hand-maintained additions that
    # live in spec/tools/pypi-extra.yaml (not generated).
    pypi = convert_pypi(dep_dir)
    extra_file = Path(__file__).with_name("pypi-extra.yaml")
    extra = yaml.safe_load(extra_file.read_text(encoding="utf-8")) if extra_file.exists() else {}
    packages = [{"package": p} for p in pypi["packages"]]
    for e in (extra or {}).get("packages") or []:
        n = norm_pypi(e["package"])
        if n not in pypi["packages"]:
            packages.append({"package": n, **({"note": e["note"]} if e.get("note") else {})})
    rule = {
        "id": "dep.pypi",
        "kind": "dependency",
        "ecosystem": "pypi",
        "name": "Cryptographic Python packages",
        "description": ("Python packages that implement or wrap cryptography, matched by PEP 503 "
                        "normalised name in requirements files, pyproject.toml, Pipfile.lock and "
                        "poetry.lock."),
        "asset": {"type": "library"},
        "packages": packages,
    }
    src_note = ", ".join(pypi["sources"]) + " + spec/tools/pypi-extra.yaml"
    (args.out / "dependencies").mkdir(parents=True, exist_ok=True)
    (args.out / "dependencies" / "dep.pypi.yaml").write_text(
        HEADER.format(src=src_note) + dump(rule), encoding="utf-8")
    print(f"java={counts['java']} python={counts['python']} pypi_packages={len(packages)}")


if __name__ == "__main__":
    main()
